#!/usr/bin/env python3
"""Generate C admission bounds/defaults from the single Python FX contract."""
from pathlib import Path
import sys
import argparse
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'src'))
from channel_fx import parameters,CHARACTERS
lines=['/* Generated by scripts/generate-fx.py; edit channel_fx.py. */','#define NP 24','static const float fx_specs[6][NP][3]={']
for ch in range(6):
    lines.append('{'+','.join('{%s,%s,%s}'%tuple('%.9gf'%v if '.' in ('%.9g'%v) else '%.9g.0f'%v for v in (p.low,p.high,p.default)) for p in parameters(ch))+'},')
lines.append('};')
lines.append('static const int character_kind[6]={'+','.join(str(c[1]) for c in CHARACTERS)+'};')
lines.append('static const float character_hz[6]={'+','.join(str(c[2])+'.0f' for c in CHARACTERS)+'};\n')
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
path=ROOT/'src/fx_specs.h';generated='\n'.join(lines)
if a.check:
    if path.read_text()!=generated:raise SystemExit('fx_specs.h needs regeneration')
else:path.write_text(generated)
